/** A check can be confirmed for this long. */
export const CHECK_VALID_MINUTES = 60;
export const MAX_IMPORT_FILE_BYTES = 5 * 1024 * 1024;

/** A file the owner uploaded, kept on disk (private) for the length of the request. */
export interface UploadedOnDisk {
  path: string;
  originalname: string;
  size: number;
}

/**
 * Images in bulk: a product is ready (complete, images included) or
 * rejected - never «missing images». Between them: complete except for its
 * barcode (none written, or a wrong one) - fixed on the check itself (typed /
 * scanned, or generated by the system), never a reason to edit the file.
 */
type ProductStatus = 'ready' | 'needs_barcode' | 'rejected';
interface CheckedProduct {
  ref: string;
  title: string;
  status: ProductStatus;
  product_row: number;
  colors: number;
  versions: number;
  branches: number;
  errors: ImportProblem[];
  warnings: ImportProblem[];
  /** Why it needs a barcode before its draft is created (status needs_barcode). */
  barcode_problems?: ImportProblem[];
  /** Its images from the ZIP: per colour (the main one included) and shared. */
  images: number;
  image_colors: { name: string; count: number }[];
  shared_images: number;
  /** A product or draft of the store that looks the same - skipped unless chosen. */
  duplicate_of: {
    kind: 'product' | 'draft' | 'file';
    id: string | null;
    title: string;
  } | null;
  /** Kept on the server only (never sent back): the draft to create. */
  payload?: DraftPayload;
}
export interface ZipSummary {
  file_name: string;
  sha256: string;
  bytes: number;
  /** Images read, checked and kept (privately) for this check. */
  staged: number;
  /** Files in the ZIP no row of «الصور» names: not kept (a warning, never silent). */
  unused: string[];
  unused_count: number;
  /** System files skipped on purpose (__MACOSX, .DS_Store, Thumbs.db). */
  ignored: string[];
  ignored_count: number;
}
interface CheckResult {
  products: CheckedProduct[];
  file_problems: ImportProblem[];
  same_file: { batch_id: string; at: string } | null;
  zip?: ZipSummary;
}
const LIST_CAP = 200;

/** Removes a check's staged images (never throws). */
export async function removeStaging(
  vendorId: string,
  batchId: string,
  logger?: Logger,
) {
  try {
    await rm(stagingDirOf(vendorId, batchId), { recursive: true, force: true });
  } catch (err) {
    logger?.warn(
      `Could not remove the import staging of ${batchId}: ${(err as Error).message}`,
    );
  }
}

async function readHead(file: string, n: number): Promise<Buffer> {
  const chunks: Buffer[] = [];
  for await (const c of createReadStream(file, { start: 0, end: n - 1 }))
    chunks.push(c as Buffer);
  return Buffer.concat(chunks);
}

async function sha256Of(file: string): Promise<string> {
  const h = createHash('sha256');
  for await (const c of createReadStream(file)) h.update(c as Buffer);
  return h.digest('hex');
}

/** The draft with each staged image replaced by its final public URL. */
function swapStaged(
  p: DraftPayload,
  url: (staged: string) => string,
): DraftPayload {
  const swap = (u: string) =>
    u.startsWith(STAGED_PREFIX) ? url(u.slice(STAGED_PREFIX.length)) : u;
  return {
    ...p,
    colors: (p.colors ?? []).map((c) => ({ ...c, images: c.images.map(swap) })),
    ...(p.shared_images ? { shared_images: p.shared_images.map(swap) } : {}),
  };
}

const fail = (
  status: 400 | 404 | 409,
  code: string,
  message: string,
  details?: unknown,
) =>
  new HttpException({ code, message, ...(details ? { details } : {}) }, status);

/**
 * The product import (2026-11-18): an XLSX file + a ZIP of its images ->
 * complete wizard drafts (images in bulk).
 *  - check: reads the file and its ZIP and builds every product's draft
 *    with the wizard's own rules (normaliseDraftPayload, publishProblems -
 *    a product is ready only when it could be published as it is, images
 *    included). Nothing is created (no draft, product, brand request or
 *    public image): the images it names are checked, cleaned of their
 *    metadata and kept in a private staging folder; the result is kept on
 *    the server for CHECK_VALID_MINUTES;
 *  - confirm: the chosen products (never a rejected one; a likely
 *    duplicate only when chosen explicitly; the same file again only when
 *    asked) are created as complete unpublished drafts with their images -
 *    all in one transaction, or none: images copied before a failed
 *    transaction are removed again, an interrupted confirm is undone by
 *    ImportStagingSweepService. Nothing is ever published by the import.
 */
@Injectable()
export class ProductImportService {
  private readonly logger = new Logger(ProductImportService.name);

  constructor(
    private readonly prisma: PrismaService,
    private readonly taxonomy: TaxonomyService,
    private readonly drafts: OfferDraftsService,
    private readonly auditLog: AuditLogService,
    private readonly barcodes: OfferBarcodesService,
  ) {}

  private async context(vendorId: string): Promise<BuildContext> {
    const [t, branches, brands, collections] = await Promise.all([
      this.taxonomy.get(),
      this.prisma.storeBranch.findMany({
        where: { vendorId, archivedAt: null },
        orderBy: { createdAt: 'asc' },
        select: { id: true, name: true },
      }),
      this.prisma.brand.findMany({
        where: { isNoBrandSentinel: false },
        orderBy: { name: 'asc' },
        select: { id: true, name: true },
      }),
      this.prisma.storeSection.findMany({
        where: { vendorId },
        orderBy: { sortOrder: 'asc' },
        select: { id: true, name: true, nameEn: true },
      }),
    ]);
    // the codes in use (products, and other open drafts): a file row with one of them is refused
    const [offerCodes, draftRows] = await Promise.all([
      this.prisma.offerBarcode.findMany({
        where: { vendorId },
        select: { code: true, vendorOffer: { select: { titleAr: true } } },
      }),
      this.prisma.offerDraft.findMany({
        where: { vendorId, status: 'OPEN', editOfOfferId: null },
        select: { payload: true },
      }),
    ]);
    const usedBarcodes = new Map<string, string>();
    for (const d of draftRows) {
      const b = (d.payload as DraftPayload | null)?.store_barcode;
      const code =
        b?.mode === 'external'
          ? normalizeBarcode(b.code).code
          : b?.mode === 'generate'
            ? b.code
            : undefined;
      if (code)
        usedBarcodes.set(
          code,
          ((d.payload as DraftPayload).title_ar ?? '').trim(),
        );
    }
    for (const c of offerCodes) usedBarcodes.set(c.code, c.vendorOffer.titleAr);
    return {
      categories: t.categories,
      colors: t.colors,
      sizes: t.sizes,
      branches,
      brands,
      collections,
      audiences: AUDIENCES,
      usedBarcodes,
    };
  }

  /** The store's own template: its branches, brands, collections and the platform lists. */
  async template(vendorId: string, lang: 'ar' | 'en'): Promise<Buffer> {
    const ctx = await this.context(vendorId);
    const usedFields = new Set(
      Object.values(CATEGORY_SPEC_TEMPLATE).flatMap(
        (tpl) => CLOTHING_CATEGORY_TEMPLATE_FIELDS[tpl] ?? [],
      ),
    );
    return buildTemplate({
      lang,
      branches: ctx.branches,
      audiences: ctx.audiences.map((a) => ({ ar: a.nameAr, en: a.nameEn })),
      categories: ctx.categories.map((c) => ({ ar: c.nameAr, en: c.nameEn })),
      colorFamilies: ctx.colors.map((c) => ({ ar: c.nameAr, en: c.nameEn })),
      sizes: ctx.sizes.map((s) => ({ label: s.label, system: s.code })),
      brands: ctx.brands.map((b) => b.name),
      collections: ctx.collections.map((c) => ({
        ar: c.name,
        en: c.nameEn ?? c.name,
      })),
      specFields: Object.keys(SPEC_FIELD_WORDS).filter((f) =>
        usedFields.has(f),
      ),
      measureKeys: Object.keys(MEASURE_WORDS),
      fibers: [
        ...Object.values(FIBER_WORDS).map((w) => (lang === 'en' ? w.en : w.ar)),
        `${lang === 'en' ? OTHER_FIBER.en : OTHER_FIBER.ar}: …`,
      ],
      countries: countryNames(lang),
    });
  }

  /** «same product» fingerprints of the store's products and open new-product drafts. */
  private async existingFingerprints(vendorId: string) {
    const [offers, openDrafts] = await Promise.all([
      this.prisma.vendorOffer.findMany({
        where: { vendorId, status: { not: 'ARCHIVED' } },
        select: {
          id: true,
          titleAr: true,
          categories: { select: { categoryCode: true } },
          colors: { select: { nameAr: true } },
        },
      }),
      this.prisma.offerDraft.findMany({
        where: { vendorId, status: 'OPEN', editOfOfferId: null },
        select: { id: true, payload: true },
      }),
    ]);
    const map = new Map<
      string,
      { kind: 'product' | 'draft'; id: string; title: string }
    >();
    for (const o of offers) {
      for (const c of o.categories) {
        map.set(
          [
            plain(o.titleAr),
            c.categoryCode,
            o.colors
              .map((x) => normalizeColorName(x.nameAr))
              .sort()
              .join('+'),
          ].join('|'),
          { kind: 'product', id: o.id, title: o.titleAr },
        );
      }
    }
    for (const d of openDrafts) {
      const p = d.payload as DraftPayload;
      if (!p?.title_ar || !p.category) continue;
      map.set(
        [
          plain(p.title_ar),
          p.category,
          (p.colors ?? [])
            .map((x) => normalizeColorName(x.name_ar ?? ''))
            .sort()
            .join('+'),
        ].join('|'),
        { kind: 'draft', id: d.id, title: p.title_ar },
      );
    }
    return map;
  }

  /**
   * A new check replaces the store's earlier unconfirmed ones: they expire
   * now and their staged images are removed (one staging per store).
   */
  private async supersede(vendorId: string) {
    const open = await this.prisma.importBatch.findMany({
      where: { vendorId, kind: 'PRODUCT_DRAFTS', status: 'CHECKED' },
      select: { id: true },
    });
    if (open.length === 0) return;
    await this.prisma.importBatch.updateMany({
      where: { id: { in: open.map((b) => b.id) }, status: 'CHECKED' },
      data: { status: 'EXPIRED' },
    });
    for (const b of open) await removeStaging(vendorId, b.id, this.logger);
  }

  async check(
    vendorId: string,
    userId: string,
    correlationId: string,
    file: UploadedOnDisk,
    zipFile: UploadedOnDisk | null,
  ) {
    const name = file.originalname ?? '';
    const buffer =
      file.size <= MAX_IMPORT_FILE_BYTES ? await readFile(file.path) : null;
    // XLSX only (a ZIP container): no CSV, no old .xls
    if (
      !/\.xlsx$/i.test(name) ||
      !buffer ||
      buffer.subarray(0, 2).toString('latin1') !== 'PK'
    ) {
      throw fail(
        400,
        buffer ? 'IMPORT_XLSX_ONLY' : 'IMPORT_XLSX_TOO_LARGE',
        buffer
          ? 'Only an .xlsx file made from the template can be imported'
          : 'The .xlsx file is larger than 5 MB',
      );
    }
    // images in bulk: the ZIP of images is part of every import
    if (!zipFile)
      throw fail(
        400,
        'IMPORT_ZIP_REQUIRED',
        'A .zip file of the products’ images must be uploaded with the .xlsx file',
      );
    const zipName = zipFile.originalname ?? '';
    const zipHead = await readHead(zipFile.path, 4);
    if (
      !/\.zip$/i.test(zipName) ||
      !['PK\u0003\u0004', 'PK\u0005\u0006'].includes(zipHead.toString('latin1'))
    )
      throw fail(400, 'IMPORT_ZIP_ONLY', 'The images must be one .zip file');
    if (zipFile.size > MAX_ZIP_BYTES)
      throw fail(
        400,
        'IMPORT_ZIP_TOO_LARGE',
        'The .zip file is larger than 150 MB',
      );
    let sheets;
    try {
      sheets = await readWorkbook(buffer);
    } catch {
      throw fail(
        400,
        'IMPORT_UNREADABLE',
        'The file could not be read as an .xlsx workbook',
      );
    }
    const sha256 = createHash('sha256').update(buffer).digest('hex');
    const zipSha256 = await sha256Of(zipFile.path);
    await this.supersede(vendorId);

    const batchId = randomUUID();
    const dir = stagingDirOf(vendorId, batchId);
    await mkdir(dir, { recursive: true });
    try {
      const ctx = await this.context(vendorId);
      const built = buildDrafts(sheets, ctx);
      const familyName = await this.drafts.familyNames();
      const existing = await this.existingFingerprints(vendorId);
      const inFile = new Map<string, string>();

      // the images: only the files «الصور» names are read, checked and staged
      const imageSheet = readImageSheet(sheets);
      const index = await openZipIndex(zipFile.path);
      const found = new Map<number, { key: string } | { code: string }>();
      const images = new Map<string, StagedImage>();
      let linked: ReturnType<typeof linkImages>;
      let unused: string[] = [];
      try {
        if (index.problems.length === 0) {
          for (const r of imageSheet.rows) {
            if (!r.file) continue;
            const f = resolveImageName(index, r.file);
            found.set(r.row, f);
            if ('key' in f && !images.has(f.key))
              images.set(f.key, await stageImage(index, f.key, dir));
          }
          unused = [...index.entries.values()]
            .filter((e) => !images.has(e.key))
            .map((e) => e.name);
        }
        linked = linkImages(built.products, imageSheet, found, images);
      } finally {
        closeZip(index);
      }
      const zipRefused = index.problems.length > 0;
      const sheetRefused = imageSheet.problems.some(
        (p) => p.code !== 'UNKNOWN_COLUMN',
      );

      const products: CheckedProduct[] = [];
      for (const b of built.products) {
        const errors = [...b.errors];
        const warnings = [...b.warnings];
        const li = linked.byRef.get(b.ref);
        if (zipRefused)
          errors.push({
            sheet: 'zip',
            row: null,
            column: null,
            code: 'ZIP_REFUSED',
          });
        else if (sheetRefused)
          errors.push({
            sheet: 'images',
            row: null,
            column: null,
            code: 'IMAGES_SHEET_INVALID',
          });
        else if (li) {
          errors.push(...li.errors);
          warnings.push(...li.warnings);
        }
        let payload: DraftPayload | null =
          errors.length === 0 && b.payload && li
            ? {
                ...b.payload,
                colors: (b.payload.colors ?? []).map((c) => ({
                  ...c,
                  images: (li.colors[c.key] ?? []).map(
                    (s) => STAGED_PREFIX + s,
                  ),
                })),
                ...(li.shared.length
                  ? { shared_images: li.shared.map((s) => STAGED_PREFIX + s) }
                  : {}),
              }
            : null;
        if (payload) {
          // the wizard's own rules decide - one source of truth
          try {
            payload = normaliseDraftPayload(
              payload,
              (url) =>
                url.startsWith(STAGED_PREFIX)
                  ? null
                  : 'IMPORT_IMAGE_NOT_STAGED',
              familyName,
            );
          } catch (err) {
            const resp =
              err instanceof HttpException
                ? (err.getResponse() as { message?: string })
                : null;
            errors.push({
              sheet: 'products',
              row: b.productRow,
              column: null,
              code: 'DRAFT_RULE',
              value: resp?.message ?? 'invalid',
            });
            payload = null;
          }
        }
        // the barcode's problems never refuse the product: it is fixed here
        const barcodeProblems: ImportProblem[] = [...b.barcodeErrors];
        if (payload) {
          // complete means publishable: the publish gate itself, images included
          // (its barcode apart: missing or wrong, the product waits on this
          // check for one - typed, scanned or generated - and is then ready)
          const all = (
            await this.drafts.publishProblems(this.prisma, vendorId, {
              id: 'import-check',
              payload: payload as Prisma.JsonValue,
              editOfOfferId: null,
            } as unknown as OfferDraft)
          ).problems;
          const problems = all.filter(
            (p) => !p.code.startsWith('STORE_BARCODE:'),
          );
          for (const code of new Set(problems.map((p) => p.code.split(':')[0])))
            errors.push({
              sheet: 'products',
              row: b.productRow,
              column: null,
              code: 'NOT_PUBLISHABLE',
              value: code,
            });
          if (problems.length > 0) payload = null;
          else if (barcodeProblems.length === 0)
            for (const p of all) {
              const [, code, value] = p.code.split(':');
              barcodeProblems.push({
                sheet: 'products',
                row: b.productRow,
                column: null,
                code: code ?? 'BARCODE_MISSING',
                ...(value ? { value } : {}),
              });
            }
        }
        let duplicate: CheckedProduct['duplicate_of'] = null;
        if (b.fingerprint) {
          const hit = existing.get(b.fingerprint);
          if (hit) duplicate = hit;
          else if (inFile.has(b.fingerprint))
            duplicate = {
              kind: 'file',
              id: null,
              title: inFile.get(b.fingerprint)!,
            };
          else inFile.set(b.fingerprint, b.ref);
        }
        const status: ProductStatus =
          errors.length > 0 || !payload
            ? 'rejected'
            : barcodeProblems.length > 0
              ? 'needs_barcode'
              : 'ready';
        // refused for another reason: the file is edited anyway - its barcode problem is named too
        if (status === 'rejected') errors.push(...barcodeProblems);
        products.push({
          ref: b.ref,
          title: b.title,
          status,
          product_row: b.productRow,
          colors: b.colorKeys.length,
          versions: Object.values(b.payload?.sizes ?? {}).reduce(
            (n, s) => n + s.length,
            0,
          ),
          branches: Object.keys(b.payload?.stock ?? {}).length,
          errors,
          warnings,
          images: li?.count ?? 0,
          image_colors: b.colorKeys.map((c) => ({
            name: c.name,
            count: li?.colors[c.key]?.length ?? 0,
          })),
          shared_images: li?.shared.length ?? 0,
          duplicate_of: duplicate,
          ...(status === 'needs_barcode'
            ? { barcode_problems: barcodeProblems }
            : {}),
          ...(status !== 'rejected' && payload ? { payload } : {}),
        });
      }

      // keep only the images a ready product uses
      const kept = new Set(
        products
          .filter((p) => p.payload)
          .flatMap((p) => payloadImageUrls(p.payload!))
          .map((u) => u.slice(STAGED_PREFIX.length)),
      );
      for (const f of await readdir(dir))
        if (!kept.has(f))
          await unlink(path.join(dir, f)).catch(() => undefined);

      const previous = await this.prisma.importBatch.findFirst({
        where: {
          vendorId,
          kind: 'PRODUCT_DRAFTS',
          status: 'CONFIRMED',
          fileSha256: sha256,
        },
        orderBy: { completedAt: 'desc' },
        select: { id: true, completedAt: true },
      });
      const result: CheckResult = {
        products,
        file_problems: [
          ...built.fileProblems,
          ...imageSheet.problems,
          ...index.problems,
          ...linked.fileProblems,
        ],
        same_file: previous
          ? {
              batch_id: previous.id,
              at: (previous.completedAt ?? new Date()).toISOString(),
            }
          : null,
        zip: {
          file_name: zipName.slice(0, 200),
          sha256: zipSha256,
          bytes: zipFile.size,
          staged: kept.size,
          unused: unused.slice(0, LIST_CAP),
          unused_count: unused.length,
          ignored: index.ignored.slice(0, LIST_CAP),
          ignored_count: index.ignored.length,
        },
      };
      const batch = await this.prisma.importBatch.create({
        data: {
          id: batchId,
          vendorId,
          kind: 'PRODUCT_DRAFTS',
          status: 'CHECKED',
          fileName: name.slice(0, 200),
          totalRows: products.length,
          fileSha256: sha256,
          zipFileName: zipName.slice(0, 200),
          zipSha256,
          zipBytes: zipFile.size,
          imagesStaged: kept.size,
          checkResult: result as unknown as Prisma.InputJsonValue,
          expiresAt: new Date(Date.now() + CHECK_VALID_MINUTES * 60_000),
          productsRejected: products.filter((p) => p.status === 'rejected')
            .length,
          createdBy: userId,
        },
      });
      await this.auditLog.record({
        actorId: userId,
        correlationId,
        action: 'product_import.checked',
        entityType: 'ImportBatch',
        entityId: batch.id,
        afterState: {
          file_name: batch.fileName,
          file_sha256: sha256,
          zip_file_name: zipName.slice(0, 200),
          zip_sha256: zipSha256,
          images_staged: kept.size,
          products: products.length,
          rejected: batch.productsRejected,
        },
      });
      return this.dto(
        batch.id,
        batch.fileName,
        sha256,
        batch.expiresAt!,
        result,
      );
    } catch (err) {
      // nothing of a failed check stays: no batch, no staged image
      await removeStaging(vendorId, batchId, this.logger);
      throw err;
    }
  }

  private dto(
    batchId: string,
    fileName: string,
    sha256: string,
    expiresAt: Date,
    r: CheckResult,
  ) {
    return {
      batch_id: batchId,
      file_name: fileName,
      file_sha256: sha256,
      expires_at: expiresAt.toISOString(),
      same_file: r.same_file,
      file_problems: r.file_problems,
      zip: r.zip ?? null,
      // the built drafts stay on the server (never trusted back from the client)
      products: r.products.map((p) => this.productDto(p)),
    };
  }

  /** One checked product as the screen sees it (its draft stays here). */
  private productDto(full: CheckedProduct) {
    const p = { ...full };
    delete p.payload;
    return {
      ...p,
      barcode_problems: full.barcode_problems ?? [],
      barcode: storeBarcodeOf(full.payload),
      selectable: p.status === 'ready',
      // a likely duplicate is skipped unless chosen explicitly
      selected_by_default: p.status === 'ready' && !p.duplicate_of,
    };
  }

  /**
   * The check, locked for a barcode change: the store's own, CHECKED and
   * not expired (a confirmed / expired one cannot change any more).
   */
  private async lockCheck(
    tx: Prisma.TransactionClient,
    vendorId: string,
    batchId: string,
  ) {
    await tx.$queryRaw`SELECT id FROM import_batches WHERE id = ${batchId} AND "vendorId" = ${vendorId} FOR UPDATE`;
    const batch = await tx.importBatch.findFirst({
      where: { id: batchId, vendorId, kind: 'PRODUCT_DRAFTS' },
      select: { id: true, status: true, expiresAt: true, checkResult: true },
    });
    if (!batch)
      throw new NotFoundException({
        code: 'IMPORT_NOT_FOUND',
        message: 'Import not found',
      });
    if (batch.status === 'CONFIRMED' || batch.status === 'CONFIRMING')
      throw fail(
        409,
        'IMPORT_ALREADY_CONFIRMED',
        'This check was already imported',
      );
    if (
      batch.status !== 'CHECKED' ||
      !batch.expiresAt ||
      batch.expiresAt.getTime() < Date.now()
    )
      throw fail(
        409,
        'IMPORT_EXPIRED',
        'This check has expired - check the file again',
      );
    return { batch, result: batch.checkResult as unknown as CheckResult };
  }

  /** A product of the check that can take a barcode (complete apart from it, or ready). */
  private fixable(result: CheckResult, ref: string) {
    const p = result.products.find((x) => x.ref === ref);
    if (!p)
      throw fail(
        400,
        'IMPORT_UNKNOWN_PRODUCT',
        `No product ${ref} in this check`,
        {
          ref,
        },
      );
    if (p.status === 'rejected' || !p.payload)
      throw fail(
        400,
        'IMPORT_PRODUCT_REJECTED',
        `Product ${ref} did not pass the check`,
        { ref },
      );
    return p;
  }

  private withBarcode(
    p: CheckedProduct,
    barcode: NonNullable<DraftPayload['store_barcode']>,
  ) {
    p.payload = { ...p.payload!, store_barcode: barcode };
    p.status = 'ready';
    delete p.barcode_problems;
  }

  /**
   * A product's barcode typed or scanned on the check (before any draft):
   * a valid code no product, open draft or other product of this check
   * uses - then the product is ready (and chosen by the screen).
   */
  async setBarcode(
    vendorId: string,
    userId: string,
    correlationId: string,
    batchId: string,
    ref: string,
    raw: string,
  ) {
    const normalized = normalizeBarcode(raw);
    if (!normalized.ok)
      throw fail(400, normalized.problem, 'This is not a valid barcode');
    return this.prisma.$transaction(async (tx) => {
      const { batch, result } = await this.lockCheck(tx, vendorId, batchId);
      const p = this.fixable(result, ref);
      const code = normalized.code;
      const product = await this.barcodes.usedBy(tx, vendorId, code);
      const draft = product
        ? undefined
        : (await this.drafts.openDraftBarcodes(tx, vendorId)).get(code);
      if (product || draft !== undefined)
        throw fail(
          409,
          'BARCODE_ALREADY_USED',
          'This barcode is already used in this store',
          [
            {
              title_ar: product?.titleAr ?? draft ?? '',
              title_en: product?.titleEn ?? '',
            },
          ],
        );
      const other = result.products.find(
        (x) => x.ref !== ref && storeBarcodeOf(x.payload)?.code === code,
      );
      if (other)
        throw fail(
          409,
          'BARCODE_DUPLICATE_IN_FILE',
          'Another product of this file has this barcode',
          [{ title_ar: other.title, title_en: '' }],
        );
      this.withBarcode(p, { mode: 'external', code });
      await tx.importBatch.update({
        where: { id: batch.id },
        data: { checkResult: result as unknown as Prisma.InputJsonValue },
      });
      await this.auditLog.record(
        {
          actorId: userId,
          correlationId,
          action: 'product_import.barcode_set',
          entityType: 'ImportBatch',
          entityId: batch.id,
          afterState: { ref, code },
        },
        tx,
      );
      return this.productDto(p);
    });
  }

  /**
   * «إنشاء باركودات من النظام لـ X منتجات» on the check: one in-store code
   * for each CHOSEN product that still needs one (never for the others, never
   * twice) - then they are ready. Returns the products it changed.
   */
  async generateBarcodes(
    vendorId: string,
    userId: string,
    correlationId: string,
    batchId: string,
    refs: string[],
  ) {
    return this.prisma.$transaction(async (tx) => {
      const { batch, result } = await this.lockCheck(tx, vendorId, batchId);
      const changed: CheckedProduct[] = [];
      for (const ref of [...new Set(refs)]) {
        const p = this.fixable(result, ref);
        if (p.status !== 'needs_barcode') continue;
        const { code } = await this.barcodes.reserveInTx(tx, vendorId, {
          userId,
          correlationId,
        });
        this.withBarcode(p, { mode: 'generate', code });
        changed.push(p);
      }
      if (changed.length > 0) {
        await tx.importBatch.update({
          where: { id: batch.id },
          data: { checkResult: result as unknown as Prisma.InputJsonValue },
        });
        await this.auditLog.record(
          {
            actorId: userId,
            correlationId,
            action: 'product_import.barcodes_generated',
            entityType: 'ImportBatch',
            entityId: batch.id,
            afterState: {
              products: changed.map((p) => ({
                ref: p.ref,
                code: storeBarcodeOf(p.payload)?.code,
              })),
            },
          },
          tx,
        );
      }
      return { products: changed.map((p) => this.productDto(p)) };
    });
  }

  async confirm(
    vendorId: string,
    userId: string,
    correlationId: string,
    batchId: string,
    input: {
      refs: string[];
      include_duplicates?: string[];
      reimport_same_file?: boolean;
      expected_sha256: string;
    },
  ) {
    const batch = await this.prisma.importBatch.findFirst({
      where: { id: batchId, vendorId, kind: 'PRODUCT_DRAFTS' },
    });
    if (!batch)
      throw new NotFoundException({
        code: 'IMPORT_NOT_FOUND',
        message: 'Import not found',
      });
    if (batch.status === 'CONFIRMED' || batch.status === 'CONFIRMING')
      throw fail(
        409,
        'IMPORT_ALREADY_CONFIRMED',
        'This check was already imported',
      );
    if (
      batch.status !== 'CHECKED' ||
      !batch.expiresAt ||
      batch.expiresAt.getTime() < Date.now()
    ) {
      if (batch.status === 'CHECKED') {
        await this.prisma.importBatch.updateMany({
          where: { id: batch.id, status: 'CHECKED' },
          data: { status: 'EXPIRED' },
        });
        await removeStaging(vendorId, batch.id, this.logger);
      }
      throw fail(
        409,
        'IMPORT_EXPIRED',
        'This check has expired - check the file again',
      );
    }
    if (input.expected_sha256 !== batch.fileSha256)
      throw fail(
        409,
        'IMPORT_FILE_CHANGED',
        'The file does not match this check',
      );
    const result = batch.checkResult as unknown as CheckResult;
    if (result.same_file && !input.reimport_same_file)
      throw fail(
        409,
        'IMPORT_SAME_FILE',
        'This same file was imported before - confirm importing it again',
        result.same_file,
      );

    const byRef = new Map(result.products.map((p) => [p.ref, p]));
    const chosen = [...new Set(input.refs)];
    if (chosen.length === 0)
      throw fail(400, 'IMPORT_NOTHING_CHOSEN', 'Choose at least one product');
    for (const ref of chosen) {
      const p = byRef.get(ref);
      if (!p)
        throw fail(
          400,
          'IMPORT_UNKNOWN_PRODUCT',
          `No product ${ref} in this check`,
          { ref },
        );
      if (p.status === 'needs_barcode')
        throw fail(
          400,
          'IMPORT_PRODUCT_NEEDS_BARCODE',
          `Product ${ref} needs a barcode before its draft is created`,
          { ref },
        );
      if (p.status !== 'ready' || !p.payload)
        throw fail(
          400,
          'IMPORT_PRODUCT_REJECTED',
          `Product ${ref} did not pass the check`,
          { ref },
        );
    }
    const includeDup = new Set(input.include_duplicates ?? []);
    const toCreate = chosen
      .map((ref) => byRef.get(ref)!)
      .filter((p) => !p.duplicate_of || includeDup.has(p.ref));
    const skipped = [
      ...chosen
        .map((ref) => byRef.get(ref)!)
        .filter((p) => p.duplicate_of && !includeDup.has(p.ref))
        .map((p) => ({
          ref: p.ref,
          title: p.title,
          reason: 'DUPLICATE' as const,
          duplicate_of: p.duplicate_of,
        })),
      ...result.products
        .filter((p) => p.status === 'rejected')
        .map((p) => ({
          ref: p.ref,
          title: p.title,
          reason: 'REJECTED' as const,
          duplicate_of: null,
        })),
      ...result.products
        .filter((p) => p.status === 'needs_barcode')
        .map((p) => ({
          ref: p.ref,
          title: p.title,
          reason: 'NEEDS_BARCODE' as const,
          duplicate_of: null,
        })),
      ...result.products
        .filter((p) => p.status === 'ready' && !chosen.includes(p.ref))
        .map((p) => ({
          ref: p.ref,
          title: p.title,
          reason: 'NOT_CHOSEN' as const,
          duplicate_of: null,
        })),
    ];
    if (toCreate.length === 0)
      throw fail(
        400,
        'IMPORT_NOTHING_CHOSEN',
        'Every chosen product was skipped as a likely duplicate',
      );

    // the store may have changed since the check: what a draft points at must still be there
    const branchIds = [
      ...new Set(toCreate.flatMap((p) => Object.keys(p.payload!.stock ?? {}))),
    ];
    const brandIds = [
      ...new Set(
        toCreate
          .map((p) =>
            p.payload!.brand?.mode === 'existing'
              ? p.payload!.brand.brand_id
              : null,
          )
          .filter((x): x is string => !!x),
      ),
    ];

    // each staged image gets its final, random public name - written down
    // BEFORE any file is copied, so an interrupted confirm can be undone
    const planned = new Map<string, string>();
    for (const p of toCreate)
      for (const url of payloadImageUrls(p.payload!)) {
        const staged = url.slice(STAGED_PREFIX.length);
        if (!planned.has(staged))
          planned.set(
            staged,
            `${randomBytes(16).toString('hex')}${path.extname(staged)}`,
          );
      }
    // once only: a second confirm (a double click, two tabs) finds it taken
    const claim = await this.prisma.importBatch.updateMany({
      where: {
        id: batch.id,
        status: 'CHECKED',
        expiresAt: { gt: new Date() },
      },
      data: {
        status: 'CONFIRMING',
        confirmStartedAt: new Date(),
        plannedUploads: [...planned.values()],
      },
    });
    if (claim.count !== 1) {
      const now = await this.prisma.importBatch.findUnique({
        where: { id: batch.id },
        select: { status: true },
      });
      throw now?.status === 'CONFIRMED' || now?.status === 'CONFIRMING'
        ? fail(
            409,
            'IMPORT_ALREADY_CONFIRMED',
            'This check was already imported',
          )
        : fail(
            409,
            'IMPORT_EXPIRED',
            'This check has expired - check the file again',
          );
    }

    const dir = stagingDirOf(vendorId, batch.id);
    const target = path.join(uploadsDir(), 'vendors', vendorId);
    const copied: string[] = [];
    let created: { ref: string; title: string; draft_id: string }[];
    try {
      await mkdir(target, { recursive: true });
      for (const [staged, final] of planned) {
        try {
          await copyFile(
            path.join(dir, staged),
            path.join(target, final),
            fsConstants.COPYFILE_EXCL,
          );
        } catch (err) {
          if ((err as NodeJS.ErrnoException).code === 'ENOENT')
            throw fail(
              409,
              'IMPORT_EXPIRED',
              'The images of this check are no longer kept - check the files again',
            );
          throw err;
        }
        copied.push(final);
      }
      const familyName = await this.drafts.familyNames();
      const payloads = toCreate.map((p) =>
        normaliseDraftPayload(
          swapStaged(p.payload!, (staged) =>
            ownUploadUrl(vendorId, planned.get(staged)!),
          ),
          (url) => ownUploadProblem(url, vendorId),
          familyName,
        ),
      );
      created = await this.prisma.$transaction(
        async (tx) => {
          const [branches, brands] = await Promise.all([
            tx.storeBranch.count({
              where: { id: { in: branchIds }, vendorId, archivedAt: null },
            }),
            tx.brand.count({ where: { id: { in: brandIds } } }),
          ]);
          if (branches !== branchIds.length || brands !== brandIds.length)
            throw fail(
              409,
              'IMPORT_STALE',
              'A branch or brand in this file changed since the check - check the file again',
            );

          const out: { ref: string; title: string; draft_id: string }[] = [];
          for (const [i, p] of toCreate.entries()) {
            const d = await tx.offerDraft.create({
              data: {
                vendorId,
                createdByUserId: userId,
                payload: payloads[i] as Prisma.InputJsonValue,
                // the draft owns its images: discarding, abandoning or
                // publishing it cleans them like any draft's
                uploads: payloadImageUrls(payloads[i]),
                importBatchId: batch.id,
                importRef: p.ref,
              },
            });
            await this.auditLog.record(
              {
                actorId: userId,
                correlationId,
                action: 'offer_draft.created',
                entityType: 'OfferDraft',
                entityId: d.id,
                afterState: {
                  import_batch_id: batch.id,
                  import_ref: p.ref,
                  images: payloadImageUrls(payloads[i]).length,
                },
              },
              tx,
            );
            out.push({ ref: p.ref, title: p.title, draft_id: d.id });
          }
          const done = await tx.importBatch.updateMany({
            where: { id: batch.id, status: 'CONFIRMING' },
            data: {
              status: 'CONFIRMED',
              completedAt: new Date(),
              draftsCreated: out.length,
              importedCount: out.length,
              skippedCount: skipped.length,
              plannedUploads: Prisma.DbNull,
            },
          });
          if (done.count !== 1)
            throw fail(
              409,
              'IMPORT_EXPIRED',
              'This check has expired - check the file again',
            );
          await this.auditLog.record(
            {
              actorId: userId,
              correlationId,
              action: 'product_import.confirmed',
              entityType: 'ImportBatch',
              entityId: batch.id,
              afterState: {
                drafts: out.map((x) => x.draft_id),
                images: planned.size,
                skipped: skipped.map((s) => ({ ref: s.ref, reason: s.reason })),
                reimport_same_file: Boolean(result.same_file),
              },
            },
            tx,
          );
          return out;
        },
        { timeout: 60_000 },
      );
    } catch (err) {
      // all or nothing: the copied images go, the check can be confirmed again
      for (const f of copied)
        await unlink(path.join(target, f)).catch(() => undefined);
      await this.prisma.importBatch
        .updateMany({
          where: { id: batch.id, status: 'CONFIRMING' },
          data: {
            status: 'CHECKED',
            confirmStartedAt: null,
            plannedUploads: Prisma.DbNull,
          },
        })
        .catch(() => undefined);
      throw err;
    }
    await removeStaging(vendorId, batch.id, this.logger);
    return { batch_id: batch.id, created, skipped };
  }

  /**
   * A staged image's thumbnail, for the check's result: the main image of
   * a ready product - only for the store that checked it, only while its
   * check is CHECKED and not expired (afterwards, or for anyone else, the
   * same 404: nothing is revealed). Never the staged file itself, never a
   * public URL: a small re-encoded copy, sent privately (no-store).
   */
  async thumbnail(vendorId: string, batchId: string, ref: string) {
    const gone = () =>
      new NotFoundException({
        code: 'IMPORT_PREVIEW_GONE',
        message: 'This preview is no longer available',
      });
    const batch = await this.prisma.importBatch.findFirst({
      where: { id: batchId, vendorId, kind: 'PRODUCT_DRAFTS' },
      select: { status: true, expiresAt: true, checkResult: true },
    });
    if (
      !batch ||
      batch.status !== 'CHECKED' ||
      !batch.expiresAt ||
      batch.expiresAt.getTime() < Date.now()
    )
      throw gone();
    const p = (batch.checkResult as unknown as CheckResult).products.find(
      (x) => x.ref === ref && x.payload,
    );
    const first = p?.payload?.colors?.[0]?.images?.[0] ?? '';
    const name = first.slice(STAGED_PREFIX.length);
    if (
      !first.startsWith(STAGED_PREFIX) ||
      !/^[0-9a-f]{64}\.(jpg|png|webp)$/.test(name)
    )
      throw gone();
    try {
      // the bytes, not the path: libvips cannot open some Windows paths
      const bytes = await readFile(
        path.join(stagingDirOf(vendorId, batchId), name),
      );
      return await sharp(bytes, { limitInputPixels: 25_000_000 })
        .resize({ width: 240, height: 320, fit: 'cover' })
        .webp({ quality: 78 })
        .toBuffer();
    } catch {
      throw gone();
    }
  }

  /**
   * One import's own drafts (never the store's other drafts): the batch's
   * screen after confirming - each draft's main image, counts and state
   * (open / published / closed), and the file's products that were not
   * created, with why. Paged.
   */
  async batchView(vendorId: string, batchId: string, page = 1, pageSize = 24) {
    const batch = await this.prisma.importBatch.findFirst({
      where: { id: batchId, vendorId, kind: 'PRODUCT_DRAFTS' },
    });
    if (!batch)
      throw new NotFoundException({
        code: 'IMPORT_NOT_FOUND',
        message: 'Import not found',
      });
    const all = await this.prisma.offerDraft.findMany({
      where: { importBatchId: batch.id, vendorId },
      select: {
        id: true,
        importRef: true,
        status: true,
        offerId: true,
        revision: true,
        payload: true,
        updatedAt: true,
      },
    });
    const num = (r: string | null) => {
      const n = Number(r);
      return Number.isFinite(n) ? n : Number.MAX_SAFE_INTEGER;
    };
    all.sort(
      (a, b) =>
        num(a.importRef) - num(b.importRef) ||
        (a.importRef ?? '').localeCompare(b.importRef ?? ''),
    );
    const size = Math.min(Math.max(pageSize, 1), 60);
    const pages = Math.max(1, Math.ceil(all.length / size));
    const current = Math.min(Math.max(page, 1), pages);
    const state = (d: (typeof all)[number]) =>
      d.status === 'OPEN'
        ? 'OPEN'
        : d.status === 'SUBMITTED' && d.offerId
          ? 'PUBLISHED'
          : 'CLOSED';
    const result = (batch.checkResult ?? {
      products: [],
    }) as unknown as CheckResult;
    const createdRefs = new Set(all.map((d) => d.importRef));
    return {
      batch_id: batch.id,
      file_name: batch.fileName,
      zip_file_name: batch.zipFileName,
      status: batch.status,
      created_at: batch.createdAt.toISOString(),
      completed_at: batch.completedAt?.toISOString() ?? null,
      drafts_total: all.length,
      counts: {
        open: all.filter((d) => state(d) === 'OPEN').length,
        published: all.filter((d) => state(d) === 'PUBLISHED').length,
        closed: all.filter((d) => state(d) === 'CLOSED').length,
      },
      not_created: result.products
        .filter((p) => !createdRefs.has(p.ref))
        .map((p) => ({
          ref: p.ref,
          title: p.title,
          reason:
            p.status === 'rejected'
              ? ('REJECTED' as const)
              : p.status === 'needs_barcode'
                ? ('NEEDS_BARCODE' as const)
                : p.duplicate_of
                  ? ('DUPLICATE' as const)
                  : ('NOT_CHOSEN' as const),
          errors: p.status === 'rejected' ? p.errors : [],
          duplicate_of: p.duplicate_of,
        })),
      /** Every open draft of the batch (all pages) - «تحديد الكل». */
      open_ids: all.filter((d) => state(d) === 'OPEN').map((d) => d.id),
      /**
       * Each draft's label (all pages): «إضافة ملصقات المحدد إلى قائمة
       * الطباعة» adds the chosen ones, wherever they are listed.
       */
      labels: all.flatMap((d) => {
        const p = (d.payload ?? {}) as DraftPayload;
        const b = storeBarcodeOf(p);
        return b
          ? [
              {
                id: d.id,
                offer_id: d.offerId,
                title_ar: p.title_ar ?? '',
                title_en: p.title_en ?? '',
                price: draftPrice(p),
                code: b.code,
                display_code: b.display_code,
                format: b.format,
              },
            ]
          : [];
      }),
      page: current,
      pages,
      page_size: size,
      items: all.slice((current - 1) * size, current * size).map((d) => {
        const p = (d.payload ?? {}) as DraftPayload;
        const colors = p.colors ?? [];
        return {
          id: d.id,
          ref: d.importRef,
          title: p.title_ar ?? '',
          state: state(d),
          offer_id: d.offerId,
          revision: d.revision,
          thumbnail: colors[0]?.images?.[0] ?? null,
          colors: colors.length,
          sizes: Object.values(p.sizes ?? {}).reduce(
            (n, l) => n + (l?.length ?? 0),
            0,
          ),
          branches: Object.values(p.stock ?? {}).filter((per) =>
            Object.values(per ?? {}).some((q) => q > 0),
          ).length,
          images: payloadImageUrls(p).length,
          // «باركود جاهز» / «ينقصه باركود قبل النشر»
          barcode: storeBarcodeOf(p),
          updated_at: d.updatedAt.toISOString(),
        };
      }),
    };
  }

  /** The store's recent product imports. */
  async list(vendorId: string) {
    const rows = await this.prisma.importBatch.findMany({
      where: { vendorId, kind: 'PRODUCT_DRAFTS' },
      orderBy: { createdAt: 'desc' },
      take: 10,
      select: {
        id: true,
        fileName: true,
        status: true,
        totalRows: true,
        draftsCreated: true,
        productsRejected: true,
        createdAt: true,
        expiresAt: true,
      },
    });
    return rows.map((r) => ({
      id: r.id,
      file_name: r.fileName,
      status:
        r.status === 'CHECKED' &&
        r.expiresAt &&
        r.expiresAt.getTime() < Date.now()
          ? 'EXPIRED'
          : r.status,
      products: r.totalRows,
      drafts_created: r.draftsCreated,
      rejected: r.productsRejected,
      created_at: r.createdAt.toISOString(),
    }));
  }
}

/** A draft's store barcode, as the check / batch screens show it (null = none yet). */
function storeBarcodeOf(payload: DraftPayload | undefined | null) {
  const b = payload?.store_barcode;
  const code =
    b?.mode === 'external'
      ? b.code.trim()
      : b?.mode === 'generate'
        ? (b.code ?? '')
        : '';
  if (!code) return null;
  const n = normalizeBarcode(code);
  const format = n.ok ? n.format : 'CODE128';
  return {
    code: n.ok ? n.code : code,
    display_code: printableBarcode(n.ok ? n.code : code, format),
    format,
    source:
      b?.mode === 'generate' ? ('GENERATED' as const) : ('EXTERNAL' as const),
  };
}

/** A draft's price as a label prints it now: its discount applied while it runs. */
function draftPrice(p: DraftPayload): number | null {
  if (typeof p.price !== 'number' || !(p.price > 0)) return null;
  const d = p.discount;
  return computeEffectivePrice({
    basePrice: p.price,
    salePrice: d?.mode === 'sale' ? d.sale_price : null,
    discountPercent: d?.mode === 'window' ? d.percent : null,
    discountStartAt:
      d?.mode === 'window' && d.start_at ? new Date(d.start_at) : null,
    discountEndAt: d?.mode === 'window' && d.end_at ? new Date(d.end_at) : null,
  });
}
