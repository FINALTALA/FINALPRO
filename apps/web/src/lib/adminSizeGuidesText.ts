export const sgMeasure = (lang: Lang, key: SizeMeasureKey) => (lang === "en" ? EN_MEASURE : MEASURE_LABEL_AR)[key];
export const sgAudience = (lang: Lang, a: string) => (lang === "en" ? EN_AUDIENCE : AUDIENCE_LABEL_AR)[a] ?? a;

/** Arabic is exactly sizeGuideAdminError(). */
export function sgError(err: unknown, lang: Lang): string {
  if (lang === "ar") return sizeGuideAdminError(err);
  if (err instanceof ApiError && EN_ERRORS[err.code]) {
    const named = err.details
      .filter((d) => typeof d === "string" || typeof d === "number")
      .map((d) => EN_MEASURE[String(d) as SizeMeasureKey] ?? String(d));
    return named.length ? `${EN_ERRORS[err.code]}: ${named.join(", ")}` : EN_ERRORS[err.code];
  }
  return mpError(err, lang);
}
