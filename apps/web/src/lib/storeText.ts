/**
 * A message kept until render (TB-16's approach): the key of the page's own
 * words, an API failure (worded by its code, never the server's text, with
 * the key as the fallback), or text produced elsewhere and shown as given.
 */
export type UiMsg = { key: string; vars?: Record<string, string | number> } | { api: unknown; key: string } | { text: string };

export function uiMsgText(msg: UiMsg, lang: Lang): string {
  if ("text" in msg) return msg.text;
  if ("api" in msg) return msg.api instanceof ApiError ? apiErrorMessage(msg.api, lang) : translate(lang, msg.key);
  const text = translate(lang, msg.key);
  return msg.vars ? text.replace(/\{(\w+)\}/g, (all, name: string) => (msg.vars && name in msg.vars ? String(msg.vars[name]) : all)) : text;
}
