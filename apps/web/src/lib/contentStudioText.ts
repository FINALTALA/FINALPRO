export const CONTENT_PAGE_KEYS = ["HOMEPAGE", "TRENDING", "ADS", "WOMEN", "MEN", "KIDS"] as const;
export type ContentPage = (typeof CONTENT_PAGE_KEYS)[number];
export const PUBLIC_PATH: Record<ContentPage, string> = {
  HOMEPAGE: "/",
  TRENDING: "/trending",
  ADS: "/ads",
  WOMEN: "/women",
  MEN: "/men",
  KIDS: "/kids",
};

const CODED = new Set(["CONTENT_VERSION_CONFLICT", "CONTENT_NOT_PUBLISHABLE", "CONTENT_SCHEDULE_EXISTS", "SCHEDULE_TIME_AMBIGUOUS"]);
/** A Content Studio error in the admin's language (server message for the rest). */
export function contentError(e: unknown, lang: Lang, t: (k: string) => string): string {
  if (e instanceof ApiError) {
    if (CODED.has(e.code)) return t(`cs.err.${e.code}`);
    const generic = apiErrorMessage(e, lang);
    return e.message && e.code.startsWith("CONTENT_") ? e.message : generic;
  }
  return apiErrorMessage(e, lang);
}
