export function fillPos(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

export function formatIls(value: string | number, lang: Lang): string {
  const n = Number(value);
  return `${n.toLocaleString(lang === "en" ? "en-GB" : "ar", { minimumFractionDigits: 2, maximumFractionDigits: 2 })} ₪`;
}

/** The words for an API error of these screens (a network failure included). */
export function posErrorText(err: unknown, lang: Lang): string {
  if (!(err instanceof ApiError)) return translate(lang, "pos.network");
  const detail = (err.details[0] ?? {}) as { title_ar?: string; title_en?: string; status?: string };
  const title = (lang === "en" ? detail.title_en || detail.title_ar : detail.title_ar) ?? "";
  const key = `pos.e.${err.code}`;
  const text = translate(lang, key);
  if (text === key) return translate(lang, "pos.e.generic");
  return fillPos(text, {
    title,
    status: detail.status ? translate(lang, `pos.e.status.${detail.status}`) : "",
  });
}
