export type Bi = { ar: string; en: string };

/** Current language helpers for the ads page. */
export function useAdsLang() {
  const lang = useLang();
  const isArabic = lang === "ar";
  const t = useCallback((key: string, vars?: Record<string, string | number>) => {
    const s = translate(lang, key);
    return vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? "")) : s;
  }, [lang]);
  const pick = useCallback((v: Bi | undefined | null) => (v ? (isArabic ? v.ar : v.en) : ""), [isArabic]);
  return { lang, isArabic, dir: (isArabic ? "rtl" : "ltr") as "rtl" | "ltr", t, pick };
}
